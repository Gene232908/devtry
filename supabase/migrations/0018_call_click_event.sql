-- ---------------------------------------------------------------------------
-- 0018 — record "Call Now" presses on the landing page
-- ---------------------------------------------------------------------------
-- Run this in Supabase -> SQL Editor.
--
-- WHY
--
-- The navbar has two contact buttons, "Call Now" and "Message Us". Only the
-- second had an event type, so pressing Call Now recorded nothing and the
-- Overview could never answer "is anyone using it?".
--
-- `events.type` is the enum `event_type`, not free text, so allowing the value
-- in the API was not enough — Postgres rejected the insert outright with
-- `invalid input value for enum event_type: "call_click"`. The enum is the
-- authority, and this is the only place it can be extended.
--
-- SAFETY
--
-- Adding a value to an enum touches no existing rows and removes nothing. Every
-- current event keeps its type, and any code that does not know about
-- 'call_click' simply never sees one. There is no downtime and nothing to undo.
--
-- Note: `ALTER TYPE ... ADD VALUE` cannot run inside a transaction block in
-- older Postgres versions. The SQL Editor runs statements individually, so
-- pasting this as-is is fine.
-- ---------------------------------------------------------------------------

alter type public.event_type add value if not exists 'call_click';
